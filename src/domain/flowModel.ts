/**
 * 最新版コールフロー（①キーマン名なしリスト／②キーマン名ありリスト）の読解済み構造。
 *
 * - 図形ラベル・図形IDは source/flow-extraction.json（Excel DrawingML から機械抽出）と一致させる。
 * - 接続線は抽出データでは方向が保証されていないため、図形の配置（行・列）と業務上の意味から
 *   「親（前の状況）→子（次の状況）」を人手で読解し、reversed で抽出時の向きとの差を記録する。
 * - classification:
 *     S = 発話場面（台本を生成） / D = 判断・条件 / I = 情報取得結果
 *     R = 結果・状態（原則台本化しない） / N = 図中の注記（補足テキスト）
 *   F（将来運用機能）は注記の一部（電話番号調査など）に付与する。
 */
export type FlowType = "NO_KEYMAN_NAME" | "HAS_KEYMAN_NAME";
export type NodeClass = "S" | "D" | "I" | "R" | "N" | "F";
export type CoverageStatus = "COVERED" | "NO_SCRIPT_INTENDED" | "NEEDS_CONFIRMATION";

export interface FlowNode {
  shapeId: string;
  label: string; // Excel 図形ラベル（改行は空白に正規化しない。原文どおり）
  cls: NodeClass;
  parent?: string; // 読解上の親（注記の場合は注記対象の図形）
  scenes: string[]; // 関連する発話場面 scene_id
  coverage: CoverageStatus;
  note: string; // 扱いの理由・要確認事項
}

export interface FlowEdge {
  connectorId: string;
  from: string;
  to: string;
  /** true: 抽出データの endpoint_a→endpoint_b と逆向きに読解した */
  reversed: boolean;
}

export interface FlowDefinition {
  flowType: FlowType;
  sheetName: string;
  shortName: string;
  description: string;
  rootShapeId: string;
  nodes: FlowNode[];
  edges: FlowEdge[];
}

const n = (
  shapeId: string,
  label: string,
  cls: NodeClass,
  parent: string | undefined,
  scenes: string[],
  coverage: CoverageStatus,
  note: string,
): FlowNode => ({ shapeId, label, cls, parent, scenes, coverage, note });

const e = (connectorId: string, from: string, to: string, reversed = false): FlowEdge => ({
  connectorId,
  from,
  to,
  reversed,
});

